-- ── Historial: quién hizo qué y cuándo ──────────────────────────────
-- Sin llaves foráneas a lo que se registra: el historial sobrevive aunque se borre el proyecto o el cliente.
create table panel_historial (
  id bigint generated always as identity primary key,
  negocio_id uuid not null references negocios on delete cascade,
  usuario_id text references "user" ("id") on delete set null,
  quien text not null check (char_length(quien) between 1 and 80),
  accion text not null check (accion in ('crear', 'editar', 'borrar', 'marcar', 'cerrar', 'publicar')),
  entidad text not null check (entidad in ('proyecto', 'cliente', 'gasto', 'gasto-fijo', 'dias', 'paso', 'reparto', 'servicio', 'persona', 'sitio', 'ciudad')),
  entidad_id text,
  proyecto_id uuid,
  cliente_id uuid,
  titulo text not null check (char_length(titulo) between 2 and 200),
  -- [{"campo": "Valor", "antes": "$ 1.000.000", "despues": "$ 2.000.000"}]
  cambios jsonb check (cambios is null or jsonb_typeof(cambios) = 'array'),
  importante boolean not null default false,
  creado timestamptz not null default now()
);
create index panel_historial_negocio_idx on panel_historial (negocio_id, creado desc);
create index panel_historial_proyecto_idx on panel_historial (proyecto_id, creado desc) where proyecto_id is not null;
create index panel_historial_cliente_idx on panel_historial (cliente_id, creado desc) where cliente_id is not null;

-- Hasta cuándo vio cada persona sus notificaciones (para el contador de "sin leer")
create table notificaciones_vistas (
  usuario_id text not null references "user" ("id") on delete cascade,
  negocio_id uuid not null references negocios on delete cascade,
  visto_hasta timestamptz not null default now(),
  primary key (usuario_id, negocio_id)
);

-- ── Avisos al celular y computador (Web Push) ───────────────────────
create table push_suscripciones (
  id uuid primary key default gen_random_uuid(),
  usuario_id text not null references "user" ("id") on delete cascade,
  negocio_id uuid not null references negocios on delete cascade,
  endpoint text not null unique check (endpoint ~ '^https://' and char_length(endpoint) <= 1000),
  p256dh text not null check (char_length(p256dh) <= 200),
  auth text not null check (char_length(auth) <= 100),
  dispositivo text check (dispositivo is null or char_length(dispositivo) <= 120),
  creado timestamptz not null default now(),
  ultimo_envio timestamptz
);
create index push_suscripciones_usuario_idx on push_suscripciones (usuario_id);

-- Un aviso de vencimiento por proyecto, tipo y día (si el aviso diario corre dos veces, no se repite)
create table avisos_enviados (
  proyecto_id uuid not null references fin_proyectos on delete cascade,
  tipo text not null check (tipo in ('faltan-2', 'hoy', 'tarde')),
  fecha date not null,
  primary key (proyecto_id, tipo, fecha)
);

