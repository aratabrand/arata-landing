-- Clientes: país y ciudad desde las listas. Se deja de usar el correo (D-119): contacto = nombre + celular.
alter table clientes
  add column pais char(2) not null default 'CO' references paises on delete restrict,
  add column ciudad_id uuid references ciudades on delete restrict;
update clientes c set ciudad_id = ci.id
  from ciudades ci where ci.pais = 'CO' and lower(btrim(c.ciudad)) = lower(ci.nombre);
comment on column clientes.ciudad is 'Sin uso desde D-119: ahora ciudad_id.';
comment on column clientes.correo is 'Sin uso desde D-119: el contacto es nombre + celular.';
